const assert = require('node:assert/strict');
const { buildSnapshot, parseOptions, reportFilename } = require('../lib/jobs-snapshot');
function main() {
  const rows = Array.from({length: 450}, (_, i) => ({ Title: 'Technical Writer', Company: `Company ${i}`, Location: i % 2 ? 'India' : 'Germany', 'Apply Link': `https://example.test/${i}`, 'Work Arrangement': i % 3 ? 'Hybrid' : 'Remote' }));
  const input = {currentRows: rows, previousRows: [], baselineRows: [], details: [], generatedAt:'2026-09-08', currentSnapshot:'20260908-0506', previousSnapshot:'20260907-0506', baselineSnapshot:'20260901-0506'};
  const daily = buildSnapshot(input);
  assert(daily.split('\n').length <= 300);
  assert(!daily.includes('All supporting jobs'));
  assert((daily.match(/https:\/\/example.test\//g) || []).length <= 15);
  const options = parseOptions(['--region','europe','--work','hybrid','--limit','4']);
  const filtered = buildSnapshot(input,options);
  assert.equal((filtered.match(/https:\/\/example.test\//g) || []).length,4);
  for (const line of filtered.split('\n').filter(s=>s.startsWith('- ['))) assert(line.includes('Germany') && line.includes('Hybrid'));
  assert.notEqual(reportFilename(options),reportFilename(parseOptions([])));
  assert.equal(reportFilename(options),reportFilename(parseOptions(['--work','hybrid','--region','europe'])));
  const empty = buildSnapshot(input,parseOptions(['--country','canada']));
  assert(empty.includes('No matching examples'));
  assert.equal(parseOptions(['--country','uk']).country,'GB');
  assert.equal(parseOptions(['--group','technical-writing']).group,'Technical Writing');
  for (const args of [['--limit','0'],['--limit','101'],['--country','madeup'],['--region','madeup'],['--group','madeup'],['--work','madeup'],['--limit'],['--topics','--changes'],['--bogus']]) assert.throws(()=>parseOptions(args));
  const topicInput = {...input, details:rows.map(r=>({URL:r['Apply Link'],Description:'Maintain API documentation and knowledge bases.'}))};
  const topicView = buildSnapshot(topicInput,parseOptions(['--topics','--limit','3']));
  assert.equal((topicView.match(/https:\/\/example.test\//g)||[]).length,3);
  assert(topicView.includes('Source excerpt'));
  const changes = buildSnapshot(input,parseOptions(['--changes','--limit','2']));
  assert.equal((changes.match(/https:\/\/example.test\//g)||[]).length,2);
  assert(changes.includes('Weekly changes by role group'));
  const { buildSnapshotWithRemote } = require('../lib/all-remote-daily-report');
  const combined = buildSnapshotWithRemote(input);
  assert(combined.startsWith('# All Remote Jobs — Daily Comparison'));
  assert(combined.includes(daily.replace(/^(#{1,5}) /gm, '$1# ')));
  assert(combined.indexOf('## Daily Jobs Snapshot') < combined.indexOf('## US Remote Jobs'));
  assert(combined.includes('## International Remote Jobs'));
  assert(combined.includes('### Current jobs in both reports'));
  assert(combined.includes('### Added') && combined.includes('### Removed') && combined.includes('### Current jobs'));
  assert(combined.split('\n').length > 300, 'Full remote lists must not be cut by the snapshot cap.');
  assert(!filtered.includes('## US Remote Jobs'), 'Focused views must stay focused.');
  console.log('Jobs snapshot tests: PASS');
}
if (require.main === module) main();
module.exports = { main };
